#!/usr/bin/env python3
"""Compile real host C99 serializer and save unchanged bytes for Laravel feature test."""
from pathlib import Path
import argparse, hashlib, json, os, subprocess, tempfile
ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT/'scripts/phase9_b14_wire_fixture.c'

def build_bytes():
    cc = os.getenv('CC', 'gcc')
    with tempfile.TemporaryDirectory(prefix='vg-b14-wire-') as folder:
        binary = Path(folder)/('wire.exe' if os.name=='nt' else 'wire')
        compile_cmd = [cc,'-std=c99','-Wall','-Wextra','-Werror','-pedantic',
                       '-I',str(ROOT/'firmware/src'),str(SOURCE),'-lm','-o',str(binary)]
        compiled = subprocess.run(compile_cmd,cwd=ROOT,capture_output=True,text=True,timeout=60)
        if compiled.returncode: raise RuntimeError('C99_COMPILE_FAILED: '+compiled.stderr[:800])
        run = subprocess.run([str(binary)],cwd=ROOT,capture_output=True,timeout=15)
        if run.returncode or run.stderr: raise RuntimeError('C99_EXECUTION_FAILED_'+str(run.returncode))
        return run.stdout

def validate(raw):
    # A Windows C runtime can translate puts() LF to CRLF. Preserve the exact
    # generated bytes for evidence and HTTP, but accept either consistent EOL.
    assert len(raw)<=8192 and raw.endswith(b'\n')
    lf_count=raw.count(b'\n')
    crlf_count=raw.count(b'\r\n')
    assert crlf_count in (0, lf_count)  # no mixed LF / CRLF
    assert b'\r' not in raw.replace(b'\r\n', b'')  # no stray CR
    lines=raw.splitlines()
    assert len(lines)==2
    parsed=[json.loads(line) for line in lines]
    for i,p in enumerate(parsed):
        assert len(lines[i])<=4096
        assert p['schema_version']=='1.0'
        assert p['device_id']=='b14-demo-device' and p['boot_id']=='b14-boot'
        assert p['source_mode']=='simulation'
        assert set(p['channels'])=={'zero_test','bilge_level'}
        assert p['channels']['zero_test']=={'value':0,'quality':'valid'}
        assert p['channels']['bilge_level']=={'value':None,'quality':'missing'}
        assert isinstance(p['sequence'],int) and isinstance(p['uptime_ms'],int)
    assert parsed[0]['sequence']==42 and parsed[0]['uptime_ms']==0
    assert parsed[1]['sequence']==18446744073709551615
    assert parsed[1]['uptime_ms']==18446744073709551615
    assert lines[0]!=lines[1]
    return sha(raw)

def sha(raw):return hashlib.sha256(raw).hexdigest()
def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--output',required=True)
    args=parser.parse_args()
    path=Path(args.output).resolve()
    assert path.parent.is_dir() and not path.exists() and not path.is_symlink()
    raw=build_bytes()
    h=validate(raw)
    with path.open('xb') as f:f.write(raw)
    assert path.read_bytes()==raw
    print('B14_C99_JSONL=PASS_2_CASES_SHA256_'+h)
if __name__=='__main__':main()
