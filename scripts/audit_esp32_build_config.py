#!/usr/bin/env python3
"""Report build-target, Wokwi-image and unresolved hardware flash configuration."""
from __future__ import annotations
from pathlib import Path
import re
import sys

ROOT=Path(__file__).resolve().parents[1]

def main():
    ini=(ROOT/"firmware/platformio.ini").read_text(encoding="utf-8")
    wokwi=(ROOT/"firmware/wokwi.toml").read_text(encoding="utf-8")
    required=("[env:esp32dev_espidf]", "platform = espressif32@7.1.3", "board = esp32dev", "framework = espidf")
    if any(x not in ini for x in required):
        print("FAIL: PlatformIO candidate target differs from reviewed baseline",file=sys.stderr)
        return 1
    if "firmware.merged.bin" not in wokwi or "firmware.elf" not in wokwi:
        print("FAIL: Wokwi artifact paths absent",file=sys.stderr)
        return 1
    print("ESP32_CANDIDATE_TARGET: esp32dev, Espressif32 7.1.3, ESP-IDF")
    print("WOKWI_ARTIFACT_CONTRACT: PASS (merged BIN and ELF named)")
    cfg=ROOT/"firmware/sdkconfig.esp32dev_espidf"
    if cfg.exists():
        content=cfg.read_text(encoding="utf-8",errors="replace")
        flash=re.search(r'^CONFIG_ESPTOOLPY_FLASHSIZE="([^"]+)"',content,re.M)
        part=re.search(r'^CONFIG_PARTITION_TABLE_FILENAME="([^"]+)"',content,re.M)
        print(f"LOCAL_IGNORED_SDKCONFIG_FLASH: {flash.group(1) if flash else 'UNKNOWN'}")
        print(f"LOCAL_IGNORED_PARTITION_TABLE: {part.group(1) if part else 'UNKNOWN'}")
    else:
        print("LOCAL_IGNORED_SDKCONFIG: ABSENT (config may be generated by PlatformIO)")
    artifact=ROOT/"firmware/.pio/build/esp32dev_espidf/firmware.merged.bin"
    if artifact.exists():
        print(f"LOCAL_SIM_MERGED_ARTIFACT_BYTES: {artifact.stat().st_size}")
    else:
        print("LOCAL_SIM_MERGED_ARTIFACT: ABSENT")
    print("HARDWARE_FLASH_CAPACITY: TBD; no physical flash verification")
    print("BUILD_CONFIG_AUDIT: PASS (static baseline only; board flash and simulator image not reconciled as hardware)")
    return 0

if __name__=="__main__":
    raise SystemExit(main())
